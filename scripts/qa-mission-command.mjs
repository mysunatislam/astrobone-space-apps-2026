import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { chromium } from "playwright";
const out = process.env.ASTROBONE_QA_OUTPUT || ".artifacts/mission-command-qa";
const url = (process.env.ASTROBONE_QA_BASE_URL || "http://127.0.0.1:5180/").split("#")[0] + "#mission-demo";
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--use-angle=d3d11"] });
const results = [];
try {
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport }), errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(url, { waitUntil: "networkidle", timeout: 90000 });
    await page.waitForFunction(() => document.querySelector("#case-day")?.textContent === "Day 180");
    await page.waitForFunction(() => document.querySelector("#mission-human-canvas")?.dataset.ready === "true", null, { timeout: 60000 });
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
    const canvas = page.locator("#mission-human-canvas"); await canvas.scrollIntoViewIfNeeded();
    const signature = () => canvas.evaluate(source => {
      const copy = document.createElement("canvas"); copy.width = 200; copy.height = 300;
      const ctx = copy.getContext("2d"); ctx.drawImage(source, 0, 0, 200, 300);
      const data = Array.from(ctx.getImageData(0, 0, 200, 300).data);
      const points = [];
      for (let i = 0; i < data.length; i += 4) if (data[i] + data[i+1] + data[i+2] > 280) points.push([i / 4 % 200, Math.floor(i / 800)]);
      return { data, bright: points.length, minY: Math.min(...points.map(p => p[1])), maxY: Math.max(...points.map(p => p[1])) };
    });
    await page.waitForTimeout(300);
    const first = await signature(); assert.ok(first.bright > 300, "3D mesh must render");
    assert.ok(first.minY > 3 && first.maxY < 297, "full body must fit vertically");
    assert.equal(await page.evaluate(() => document.querySelector(".mission-human header").getBoundingClientRect().bottom <= document.querySelector("#mission-human-canvas").getBoundingClientRect().top + 1), true, "header cannot overlap anatomy");
    const box = await canvas.boundingBox();
    await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5); await page.mouse.down();
    await page.mouse.move(box.x + box.width * .65, box.y + box.height * .5, { steps: 8 }); await page.mouse.up();
    await page.waitForTimeout(200); const rotated = await signature();
    assert.ok(rotated.data.filter((v, i) => Math.abs(v - first.data[i]) > 20).length > 500, "human reference must respond to orbit interaction");
    await page.locator("#mission-day-slider").fill("0");
    assert.equal(await page.locator("#case-day").innerText(), "Day 1");
    assert.match(await page.locator("#case-heart-value").innerText(), /64 bpm/);
    assert.match(await page.locator("#case-dose").innerText(), /^0 mGy/);
    await page.locator("#mission-day-slider").fill("3");
    await page.locator("#mission-why").click();
    assert.match(await page.locator("#mission-explanation-body").innerText(), /165 to 151/);
    assert.match(await page.locator("#mission-explanation-body").innerText(), /not inferred/);
    await page.locator("#mission-dialog-close").click();
    await page.locator("#mission-event").click();
    assert.match(await page.locator(".scenario-notice").innerText(), /hypothetical \+10 mGy/);
    assert.match(await page.locator("#case-dose").innerText(), /^27 mGy/);
    await page.locator("#mission-dialog-close").click();
    await page.locator("#mission-handoff").click();
    const wait = page.waitForEvent("download"); await page.locator("#mission-dialog-export").click();
    const download = await wait, report = JSON.parse(await readFile(await download.path(), "utf8"));
    assert.equal(report.dose.cumulative_personal_absorbed_dose_mgy, 27);
    assert.equal(report.scenario.additionalDoseMgy, 10); assert.equal(report.explanation.day, 180);
    assert.equal(report.cardiovascular.length, 4); assert.equal(report.externalEvidence.xray.patientLinked, false);
    await page.screenshot({ path: `${out}/handoff-${viewport.width}.png`, fullPage: true });
    await page.locator("#mission-dialog-close").click();
    await page.locator("#mission-day-slider").fill("4");
    assert.match(await page.locator("#case-heart-value").innerText(), /Withheld/);
    assert.equal(await page.locator("#mission-event-reset").isVisible(), false);
    await page.locator("#mission-day-slider").fill("3");
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
    await page.screenshot({ path: `${out}/command-${viewport.width}.png`, fullPage: true });
    await page.locator("#twin-tab").click(); assert.equal(await page.locator("#upload-video").isVisible(), true);
    await page.locator("#companion-tab").click(); assert.match(page.url(), /#mission-demo$/);
    assert.equal(await canvas.isVisible(), true); assert.deepEqual(errors, []);
    await page.locator(".exit-presentation").click();
    assert.equal(await canvas.isVisible(), false);
    assert.equal(await page.locator("#mission-event").isVisible(), false);
    assert.equal(await page.locator("#case-day").innerText(), "Day 180");
    results.push({ viewport, passed: true, brightPixels: first.bright, bodyYRange: [first.minY, first.maxY], checks: ["automatic demo", "timeline", "nonblank full body", "orbit interaction", "explanation", "simulation isolated", "handoff", "quality refusal", "capture round trip"] });
    console.log(`[mission command] ${viewport.width}: passed`); await page.close();
  }
} finally { await browser.close(); await writeFile(`${out}/report.json`, JSON.stringify(results, null, 2)); }
