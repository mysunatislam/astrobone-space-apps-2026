"""Fit the shipped hybrid knee-angle model on all REHAB24-6 people and write it as JavaScript.

Writes <repo>/src/kneeHybridModel.js (the trees, the feature ranges seen in training) and
<repo>/src/kneeHybridModel.fixture.json (feature rows with sklearn's own predictions, so a test proves the
JavaScript port predicts exactly what was validated).
Usage: OMP_NUM_THREADS=1 python export_knee_hybrid.py <repo>
"""
import json, os, sys
os.environ.setdefault("OMP_NUM_THREADS", "1")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, pandas as pd
from sklearn.ensemble import HistGradientBoostingRegressor
from hybrid_pose import features, FEATURES, APP_VIS, GBM

repo = sys.argv[1]
df = pd.read_parquet("/home/user/data/pose_frames.parquet")
d = df[(df["model"] == "mp-lite") & df["detected"] & (df["vis"] >= APP_VIS) & (df["near"] | (df["view"] == "front"))]
d = d[np.isfinite(d[["est2", "est3", "yaw", "thigh2d", "shank2d"]]).all(axis=1)].reset_index(drop=True)
X, y = features(d), d["gt3"].values
model = HistGradientBoostingRegressor(**GBM).fit(X, y)
trees = []
for (pred,) in model._predictors:
    n = pred.nodes
    # One flat array per tree: [feature, threshold, left, right, missingLeft] for splits, [-1, value] for leaves.
    trees.append([[-1, round(float(r["value"]), 6)] if r["is_leaf"] else [int(r["feature_idx"]), round(float(r["num_threshold"]), 6), int(r["left"]), int(r["right"]), int(r["missing_go_to_left"])] for r in n])
ranges = np.percentile(X, [0.5, 99.5], axis=0).T
model_js = {
    "source": "REHAB24-6 (Cernek et al., 2024, CC BY-NC 4.0): 9 people, squats and lunges, Vicon motion capture; MediaPipe Pose Landmarker lite",
    "frames": int(len(d)), "people": int(d["person"].nunique()), "features": FEATURES,
    "baseline": round(float(np.ravel(model._baseline_prediction)[0]), 6),
    "ranges": [[round(float(a), 4), round(float(b), 4)] for a, b in ranges],
    "trees": trees,
}
header = ("// Generated by the real-video validation (scripts/validation/README.md): gradient-boosted trees that map the\n"
          "// pretrained pose model's knee angles, body yaw and thigh foreshortening to the motion-capture knee angle.\n"
          "// Trained on REHAB24-6 (Cernek et al. 2024, doi:10.5281/zenodo.13305826, CC BY-NC 4.0): these fitted values are\n"
          "// derived from that dataset, so they carry its attribution and non-commercial terms (THIRD_PARTY_NOTICES.md).\n"
          "// Do not edit by hand; refit and regenerate instead. See docs/real-video-validation.md.\n")
open(f"{repo}/src/kneeHybridModel.js", "w").write(header + "export const KNEE_HYBRID_MODEL = Object.freeze(" + json.dumps(model_js, separators=(",", ":")) + ");\n")
rng = np.random.default_rng(0)
pick = rng.choice(len(d), 40, replace=False)
fixture = [{"input": {"angle2d": float(d.at[i, "est2"]), "angle3d": float(d.at[i, "est3"]), "yawDeg": float(d.at[i, "yaw"]), "thigh2d": float(d.at[i, "thigh2d"]),
                      "shank2d": float(d.at[i, "shank2d"]), "visibility": float(d.at[i, "vis"])}, "expected": float(model.predict(X[i:i + 1])[0])} for i in pick]
json.dump(fixture, open(f"{repo}/src/kneeHybridModel.fixture.json", "w"), indent=0)
print("trees", len(trees), "nodes", sum(len(t) for t in trees), "frames", len(d))
